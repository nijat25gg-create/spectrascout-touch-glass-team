"""Write frontend/vocab.json from rules/gates.yaml, so the answer lists never drift from the engine.

    python3 frontend/tools/make_vocab.py            (from the repo root)

Uses engine.gates_loader.load_gates: it keeps yes/no as strings (plain YAML would turn them into
true/false). vocab.json = {attributes: {name: {values: [...without "unknown"], kind}}, rules: {id: {because, source, effect}}}.
Run it after every change of rules/gates.yaml and commit vocab.json together with it.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def build_vocab(g: dict) -> dict:
    questions = g.get("questions", {})
    return {
        # rule texts for "why it fits" / "still to check": C8 trace carries only rule id + source
        "rules": {r["id"]: {"because": r.get("because"), "source": r.get("source") or [], "effect": r.get("effect")}
                  for r in g.get("rules", []) if r.get("id")},
        "_source": "rules/gates.yaml (attributes, questions), generated by frontend/tools/make_vocab.py",
        "rules_version": str(g.get("version")),
        "attributes": {
            name: {"values": [v for v in a["values"] if v != "unknown"],
                   "kind": questions.get(name, {}).get("kind")}
            for name, a in g["attributes"].items()
        },
    }


def main(root: Path = ROOT) -> Path:
    sys.path.insert(0, str(root))
    from engine.gates_loader import load_gates
    out = root / "frontend" / "vocab.json"
    out.write_text(json.dumps(build_vocab(load_gates()), ensure_ascii=False, indent=1) + "\n")
    return out


if __name__ == "__main__":
    path = main(Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else ROOT)
    print(f"wrote {path}")
